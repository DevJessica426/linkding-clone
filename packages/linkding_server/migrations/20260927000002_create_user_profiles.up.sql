-- One row per user. Django keeps no column defaults in the database; the
-- application writes every column.
CREATE TABLE bookmarks_userprofile (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    theme character varying(10) NOT NULL,
    user_id integer NOT NULL,
    bookmark_date_display character varying(10) NOT NULL,
    bookmark_link_target character varying(10) NOT NULL,
    web_archive_integration character varying(10) NOT NULL,
    enable_sharing boolean NOT NULL,
    enable_favicons boolean NOT NULL,
    tag_search character varying(10) NOT NULL,
    display_url boolean NOT NULL,
    permanent_notes boolean NOT NULL,
    enable_public_sharing boolean NOT NULL,
    search_preferences jsonb NOT NULL,
    custom_css text NOT NULL,
    bookmark_description_display character varying(10) NOT NULL,
    bookmark_description_max_lines integer NOT NULL,
    display_archive_bookmark_action boolean NOT NULL,
    display_edit_bookmark_action boolean NOT NULL,
    display_remove_bookmark_action boolean NOT NULL,
    display_view_bookmark_action boolean NOT NULL,
    enable_automatic_html_snapshots boolean NOT NULL,
    default_mark_unread boolean NOT NULL,
    enable_preview_images boolean NOT NULL,
    tag_grouping character varying(12) NOT NULL,
    auto_tagging_rules text NOT NULL,
    items_per_page integer NOT NULL,
    sticky_pagination boolean NOT NULL,
    custom_css_hash character varying(32) NOT NULL,
    collapse_side_panel boolean NOT NULL,
    hide_bundles boolean NOT NULL,
    default_mark_shared boolean NOT NULL,
    legacy_search boolean NOT NULL,
    CONSTRAINT bookmarks_userprofile_user_id_key UNIQUE (user_id),
    CONSTRAINT bookmarks_userprofile_user_id_0dbae2c9_fk_auth_user_id
        FOREIGN KEY (user_id) REFERENCES auth_user(id) DEFERRABLE INITIALLY DEFERRED
);
